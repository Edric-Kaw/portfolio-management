import {test,expect} from '@playwright/test';
import * as XLSX from 'xlsx';
import {demoSource} from '../../src/demo.js';
test('audit headers filter, sort numeric values, and show cached values before Details',async({page})=>{
  const wb=XLSX.utils.book_new(),source=demoSource();
  for(const [name,rows] of Object.entries(source.sheets))XLSX.utils.book_append_sheet(wb,XLSX.utils.json_to_sheet(rows.map(({__row,...r})=>r)),name);
  for(const [i,value] of [42,2,10,0].entries())wb.Sheets.Asset[`H${i+2}`]={t:'n',v:value,f:String(value)};
  await page.goto('./');
  await page.locator('#file').setInputFiles({name:'synthetic-audit.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:XLSX.write(wb,{type:'buffer',bookType:'xlsx'})});
  await page.getByRole('button',{name:'Activate dataset'}).click();
  await page.locator('[data-view="quality"]').click();
  const audit=page.locator('#quality-table');
  await expect(audit.locator('thead tr').first().locator('th').nth(4)).toContainText('Value');
  await expect(audit.locator('thead tr').first().locator('th').nth(5)).toContainText('Details');
  await audit.getByRole('combobox',{name:'Filter Code',exact:true}).selectOption('FORMULA_CACHE');
  await expect(audit.getByRole('status')).toContainText('4 of');
  await audit.getByRole('button',{name:'Sort by Value',exact:true}).click();
  await expect(audit.locator('tbody tr td:nth-child(5)')).toHaveText(['0','2','10','42']);
  await audit.getByRole('button',{name:'Sort by Value',exact:true}).click();
  await expect(audit.locator('tbody tr td:nth-child(5)')).toHaveText(['42','10','2','0']);
  await audit.getByRole('searchbox',{name:'Filter Value',exact:true}).fill('10');
  await expect(audit.locator('tbody tr')).toHaveCount(1);
  await expect(audit.locator('tbody')).toContainText('BalanceInMYR uses a cached');
  await audit.getByRole('combobox',{name:'Filter Severity',exact:true}).selectOption('correction');
  await expect(audit.locator('tbody')).toContainText('No audit entries match');
  await audit.getByRole('button',{name:'Clear filters & sort'}).click();
  await expect(audit.getByRole('status')).not.toContainText('0 of');
  await page.screenshot({path:'tests/output/audit.png',fullPage:true});
  await page.locator('#reset').click();await expect(audit).toBeEmpty();
});
